#!/usr/bin/env python3
"""Generates src/title_font.h, the title screen's button font (needs Pillow). The PICO-8 text is
drawn with fontlibc from font/myfont.inc (src/pico8_font.c).

- legacy_font / legacy_spacing: font/minecraft-legacy-edition.otf as a graphx font
  (gfx_SetFontData / gfx_SetFontSpacing): 8 bytes per character, MSB left, characters 0-127.
  The OTF is drawn at 16 px, where one font pixel is 2x2, and sampled at each block's centre.
  Rows 0-6 are the capitals, row 7 the descenders; the spacing is the advance (width + 1).

Run: python3 utils/gen_title_font.py, then make clean (a new or changed header).
"""
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
OTF = ROOT / "font/minecraft-legacy-edition.otf"
OUT = ROOT / "src/title_font.h"

SIZE = 16           # 2 px per font pixel
CAP_TOP = 6         # first pixel row of a capital at SIZE when drawn at y = 0


def legacy():
    font = ImageFont.truetype(str(OTF), SIZE)
    data = []
    spacing = []
    for c in range(128):
        ch = chr(c)
        if c < 32 or c == 127:
            data += [0] * 8
            spacing.append(0)
            continue
        im = Image.new("1", (SIZE * 2, SIZE * 2), 0)
        d = ImageDraw.Draw(im)
        d.fontmode = "1"
        d.text((0, 0), ch, font=font, fill=1)
        # ',' reaches a row below the cell and '^' one above: moved into it
        box = im.getbbox()
        top = CAP_TOP
        if box:
            top = min(max(top, box[3] - 16), box[1])
        for r in range(8):
            byte = 0
            for col in range(8):
                if im.getpixel((2 * col + 1, top + 2 * r + 1)):
                    byte |= 0x80 >> col
            data.append(byte)
        # nothing may lie outside the 8x8 cell
        for y in range(im.height):
            for x in range(im.width):
                if im.getpixel((x, y)):
                    assert top <= y < top + 16 and x < 16, (ch, x, y)
        adv = round(font.getlength(ch) / 2)
        assert 0 < adv <= 9, (ch, adv)
        spacing.append(adv)
    return data, spacing


def rows(values, per_line):
    return "\n".join("    " + " ".join(f"0x{v:02x}," for v in values[i:i + per_line])
                     for i in range(0, len(values), per_line))


def main():
    data, spacing = legacy()
    OUT.write_text(f"""// Generated by utils/gen_title_font.py; don't edit. Included by title.c only.
#ifndef TITLE_FONT_H
#define TITLE_FONT_H

#include <stdint.h>

// font/minecraft-legacy-edition.otf: graphx font data (8 rows of 8 px, MSB left) and advances
static const uint8_t legacy_font[128 * 8] = {{
{rows(data, 8)}
}};
static const uint8_t legacy_spacing[128] = {{
{rows(spacing, 16)}
}};

#endif
""")


if __name__ == "__main__":
    main()
